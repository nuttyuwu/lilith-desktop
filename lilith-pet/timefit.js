// When a game line can be said, from its English text (the line ids are the same in every language).
// The game picks these by trigger (TimeMorning, TimeNight, Birthday, Neglect...); our extract only has the text,
// so the time words decide.
// Used by life.js (sayLine pool) and to list them (node timefit.js corpus.jsonl).
(function (root) {
  const DAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const RULES = [
    // tied to things we don't track (your birthday, how long you were away, yesterday, a long session)
    [/birthday|new year|christmas|halloween|valentine|yesterday|past (week|month|year)|whole (week|month|year|season)|a whole year|this past|been at (the|your) (desk|computer)|been sitting for ages/i, 'never'],
    [/morning and (good )?night|night and (good )?morning/i, null],           // "together, morning and night~": any time
    [/last night/i, [[5, 12]]],                                               // "did you dream last night?" is a morning line
    [/worked all day|how was your day/i, [[17, 24]]],
    [/\bmidnight\b|\b(so|this|too) late\b|stay(ing|ed)? up|up (so|this) late|late at night|late-night|late into the night|wee hours/i, [[23, 5]]],
    [/\bdawn\b|\bsunrise\b/i, [[4, 7]]],
    [/\btonight\b/i, [[18, 4]]],
    [/good night|night-night|nighty|bedtime|sweet dreams|sleep tight|go(ing)? to (bed|sleep)|off to bed|\bnight\b/i, [[20, 4]]],
    [/\bevening\b|\bdinner\b|\bsunset\b/i, [[17, 22]]],
    [/\bafternoon\b/i, [[12, 17]]],
    [/\bnoon\b|\blunch\b/i, [[11, 14]]],
    [/\bmorning\b|\bbreakfast\b|rise and shine|new day/i, [[5, 11]]],
  ];
  const at = (h) => [h % 24, (h + 1) % 24];
  // whenOf(en) -> null (any time) | 'never' | { ranges: [[from, to), ...], days?: [0-6] }
  function whenOf(en = '') {
    const days = [];
    if (/\bweekend\b/i.test(en)) days.push(0, 6);
    DAYS.forEach((d, i) => { if (new RegExp(`\\b${d}\\b`, 'i').test(en)) days.push(i); });
    const w = (ranges) => ({ ranges, ...(days.length && { days }) });
    // an exact clock time -> that hour only: "8 AM~", "It's 3 PM", "3 in the morning", "It's 12 o'clock" (12-hour: both)
    if (/\b12 noon\b/i.test(en)) return w([at(12)]);
    let m = /\b(\d{1,2})(?::\d{2})?\s?(am|pm|a\.m\.|p\.m\.)/i.exec(en);
    if (m) return w([at(Number(m[1]) % 12 + (/^p/i.test(m[2]) ? 12 : 0))]);
    m = /\b(\d{1,2}) in the (morning|afternoon|evening|night)/i.exec(en);
    if (m) { const h = Number(m[1]) % 12; return w([at(m[2] === 'morning' || (m[2] === 'night' && h < 5) ? h : h + 12)]); }
    m = /\b(\d{1,2}) o'clock/i.exec(en);
    if (m) { const h = Number(m[1]) % 12; return w([at(h), at(h + 12)]); }
    for (const [re, r] of RULES) if (re.test(en)) return r === 'never' ? 'never' : r ? w(r) : (days.length ? w([[0, 24]]) : null);
    return days.length ? w([[0, 24]]) : null;
  }
  const inRange = ([a, b], h) => (a <= b ? h >= a && h < b : h >= a || h < b);
  function fitsNow(when, now = new Date()) {
    if (!when) return true;
    if (when === 'never') return false;
    return when.ranges.some((r) => inRange(r, now.getHours())) && (!when.days || when.days.includes(now.getDay()));
  }
  const api = { whenOf, fitsNow };
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = api;
    if (require.main === module) {   // node timefit.js <corpus.jsonl> -> markdown list of every time-bound voiced line
      const fs = require('fs');
      const rows = fs.readFileSync(process.argv[2], 'utf8').split('\n').filter(Boolean).map((s) => JSON.parse(s)).filter((l) => l.soundId && l.en);
      const hh = (h) => `${String(h).padStart(2, '0')}:00`;
      const fmt = (w) => (w === 'never' ? 'never (needs data we don\'t track)' : w.ranges.map(([a, b]) => `${hh(a)}-${hh(b)}`).join(' & ') + (w.days ? ' ' + w.days.map((d) => DAYS[d].slice(0, 3)).join('/') : ''));
      const groups = {};
      for (const l of rows) { const w = whenOf(l.en); if (w) (groups[fmt(w)] ||= []).push(l); }
      const out = ['# Time-bound voice lines', '', `Generated by \`node timefit.js corpus.jsonl\`: ${Object.values(groups).flat().length} of ${rows.length} voiced lines. She only says a line inside its window (PC clock).`, ''];
      for (const k of Object.keys(groups).sort()) { out.push(`## ${k} (${groups[k].length})`, ''); for (const l of groups[k]) out.push(`- ${l.id}: ${l.en.replace(/\n/g, ' ')}`); out.push(''); }
      process.stdout.write(out.join('\n'));
    }
  } else root.timefit = api;
})(this);
